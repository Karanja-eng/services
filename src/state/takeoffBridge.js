/**
 * Fundi Studio — takeoff bridge (specialised tools → global taking-off).
 *
 * The global taking-off state lives in `AppLayout` (`takeoffData`) and feeds the
 * three document routes (`/quantity/manual/taking-off`, `/approximate`, `/boq`).
 * Specialised takeoffs (roof, septic) keep their own local working state — this
 * bridge is the *explicit* hand-off, not a replacement for it.
 *
 * Merge policy (deliberately conservative):
 * - Items from other sources (manual edits, other tools) are never touched.
 * - A tool re-publishing replaces only its own previous batch, so repeated
 *   "Calculate" clicks cannot accumulate duplicates.
 * - Generated items are tagged with `source` / `sourceRef` / `sourceLabel`,
 *   which are additive keys; the downstream documents ignore unknown keys and
 *   the existing item fields (`id`, `billNo`, `description`, `unit`, `quantity`,
 *   `rate`, `amount`, `dimensions`, `isHeader`) are preserved verbatim.
 *
 * All helpers are pure so they can be unit-tested without React.
 */

export const TAKEOFF_SOURCE = {
  manual: "manual",
  roof: "roof",
  septic: "septic",
};

export const SOURCE_LABELS = {
  [TAKEOFF_SOURCE.roof]: "Roof takeoff",
  [TAKEOFF_SOURCE.septic]: "Septic tank takeoff",
  [TAKEOFF_SOURCE.manual]: "Manual",
};

export const getSourceLabel = (source) => SOURCE_LABELS[source] || source || "Unknown";

/**
 * Replace the published batch for `source` with `incoming`, keeping every item
 * that came from another source in its original order.
 *
 * @param {Array<object>} existing Current global takeoff items.
 * @param {Array<object>} incoming Items generated by the tool.
 * @param {string} source Source id (see TAKEOFF_SOURCE).
 * @returns {Array<object>} New array (never mutates the inputs).
 */
export function publishSourceBatch(existing, incoming, source) {
  const safeExisting = Array.isArray(existing) ? existing : [];
  const safeIncoming = Array.isArray(incoming) ? incoming : [];
  const kept = safeExisting.filter((item) => item && item.source !== source);

  const tagged = safeIncoming.map((item, index) => ({
    ...item,
    source,
    sourceRef: `${source}:${index}`,
    sourceLabel: getSourceLabel(source),
  }));

  return [...kept, ...tagged];
}

/**
 * Remove every item published by `source`; other items are preserved.
 */
export function clearSourceBatch(existing, source) {
  const safeExisting = Array.isArray(existing) ? existing : [];
  return safeExisting.filter((item) => item && item.source !== source);
}

/**
 * Count the items currently published by `source`.
 */
export function countSourceBatch(existing, source) {
  const safeExisting = Array.isArray(existing) ? existing : [];
  return safeExisting.filter((item) => item && item.source === source).length;
}

/**
 * Stable identity for a published batch: source + number of items + the id of
 * the first and last item. Used by the tools to decide whether the "published"
 * note is stale.
 */
export function batchFingerprint(items) {
  const list = Array.isArray(items) ? items : [];
  if (list.length === 0) return "";
  const first = list[0]?.id ?? "";
  const last = list[list.length - 1]?.id ?? "";
  return `${list.length}:${first}:${last}`;
}
